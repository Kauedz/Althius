select throws_ok('select public.agent_engine_last_heartbeat()', '42501', null, 'Anônimo não lê');
reset role;
select ok((select relrowsecurity from pg_class where oid = 'private.agent_engine_heartbeat'::regclass), 'Tabela privada tem RLS');
