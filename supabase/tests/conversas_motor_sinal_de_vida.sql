select lives_ok('select public.record_agent_engine_heartbeat()', 'Próximo ciclo atualiza sinal único');
reset role;
select is((select count(*)::integer from private.agent_engine_heartbeat), 1, 'Uma única linha do motor');
set local role authenticated;
select throws_ok('select public.record_agent_engine_heartbeat()', '42501', null, 'Participante não grava');
select throws_ok('select public.agent_engine_last_heartbeat()', '42501', null, 'Participante não lê');
set local role anon;
